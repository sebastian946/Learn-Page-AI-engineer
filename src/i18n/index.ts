const messages: Record<Locale, Record<MessageKey, string>> = { en, es }

export function useLocale(): Locale {
  return useProgress((s) => s.locale)
}

/** Returns a translator for UI strings plus helpers for localized content fields. */
export function useT() {
  const locale = useLocale()
  const t = (key: MessageKey) => messages[locale][key]
  const l = (value: L10n) => value[locale] || value.en
  const ll = (value: L10nList) => (value[locale]?.length ? value[locale] : value.en)
  return { t, l, ll, locale }
}
