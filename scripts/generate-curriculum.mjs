#!/usr/bin/env node
// Regenerates CURRICULUM.md from src/content/modules/*/module.json and the exam files.
// Usage: npm run curriculum
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const modulesDir = join(root, 'src/content/modules')
const modules = readdirSync(modulesDir)
  .filter((d) => existsSync(join(modulesDir, d, 'module.json')))
  .map((d) => JSON.parse(readFileSync(join(modulesDir, d, 'module.json'), 'utf8')))
  .sort((a, b) => a.order - b.order)

const examCount = (id) => {
  const path = join(root, 'src/content/exams', `${id}.json`)
  return existsSync(path) ? JSON.parse(readFileSync(path, 'utf8')).questions.length : 0
}
const count = (m, type) => m.lessons.filter((l) => l.type === type).length
const totalHours = modules.reduce((n, m) => n + m.hours, 0)
const totalDays = modules.reduce((n, m) => n + m.days, 0)

let out = `# Curriculum — AI Engineer Learning Platform

Text-first, project-first path from Senior SDET to AI Engineer. Every module ends with artifacts for your GitHub portfolio.
All content is available in English and Spanish.

**Total:** ${modules.length} modules · ${totalDays} days · ~${totalHours} hours · ${modules.reduce((n, m) => n + m.lessons.length, 0)} lessons

> This file is generated by \`npm run curriculum\` from \`src/content/modules/*/module.json\`. Do not edit it by hand.

## Overview

| # | Module | Days | Hours | Concepts | Exercises | Exam questions | Capstone |
|---|---|---|---|---|---|---|---|
`
for (const m of modules) {
  out += `| ${m.order} | ${m.title.en} | ${m.days} | ~${m.hours} | ${count(m, 'concept')} | ${count(m, 'exercise')} | ${examCount(m.id)} | ${count(m, 'project') ? 'Yes' : '—'} |\n`
}

out += `\n## Expected GitHub repos\n\n| Module | Repo | What it proves |\n|---|---|---|\n`
for (const m of modules) for (const r of m.repos) out += `| ${m.order} | \`${r.name}\` | ${r.description.en} |\n`

out += `\n## Modules in detail\n`
for (const m of modules) {
  out += `\n### Module ${m.order} — ${m.title.en}\n\n*${m.days} day${m.days === 1 ? '' : 's'} · ~${m.hours} hours*\n\n${m.summary.en}\n\n`
  for (const l of m.lessons) {
    const time = l.minutes >= 120 ? `${Math.round(l.minutes / 60)} h` : `${l.minutes} min`
    out += `- **${l.type}** — ${l.title.en} (${time})\n`
  }
}

writeFileSync(join(root, 'CURRICULUM.md'), out)
console.log(`CURRICULUM.md written (${modules.length} modules).`)
